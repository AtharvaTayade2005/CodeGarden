/**
 * Retrieve a concept topic by unique ID
 */
export function getConceptById(id: string): ConceptTopic | undefined {
  return CONCEPTS_DATA.find((c) => c.id === id);
}

/**
 * Resolve the most relevant concept for a given exercise ID
 */
export function getConceptForExercise(exerciseId: string, conceptName?: string): ConceptTopic {
  // Direct match by exercise ID
  const directMatch = CONCEPTS_DATA.find((c) => c.relatedExerciseIds.includes(exerciseId));
  if (directMatch) return directMatch;

  // Keyword match on concept name
  if (conceptName) {
    const lower = conceptName.toLowerCase();
    if (lower.includes('input') || lower.includes('print')) return CONCEPTS_DATA[0];
    if (lower.includes('variable') || lower.includes('tuple')) return CONCEPTS_DATA[1];
    if (lower.includes('conditional') || lower.includes('if') || lower.includes('branch')) return CONCEPTS_DATA[2];
    if (lower.includes('loop') || lower.includes('for') || lower.includes('while') || lower.includes('range'))
      return CONCEPTS_DATA[3];
    if (lower.includes('function') || lower.includes('recursion') || lower.includes('def'))
      return CONCEPTS_DATA[4];
  }

  // Fallback default
  return CONCEPTS_DATA[0];
}
